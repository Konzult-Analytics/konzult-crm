"use client";

import { useActionState } from "react";
import { confirmEnrollment, startEnrollment, type EnrollState } from "../actions";

export default function EnrollForm() {
  const [setup, start, starting] = useActionState<EnrollState>(startEnrollment, null);
  const [result, confirm, confirming] = useActionState(confirmEnrollment, null);
  const enrollment = setup?.enrollment;

  if (!enrollment) {
    return (
      <form action={start} className="mt-6 space-y-4">
        {setup?.error && <p className="text-sm text-danger">{setup.error}</p>}
        <button className="btn btn-accent w-full" type="submit" disabled={starting}>
          {starting ? "Preparing…" : "Show my QR code"}
        </button>
      </form>
    );
  }

  return (
    <div className="mt-6 space-y-5">
      <ol className="list-decimal space-y-1 pl-5 text-sm text-ink-soft">
        <li>Open your authenticator app (Google Authenticator, Microsoft Authenticator or 1Password).</li>
        <li>Scan this code, or type the key below.</li>
        <li>Enter the 6-digit code the app shows.</li>
      </ol>
      {/* The QR code is an SVG data URI generated by Supabase. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={enrollment.qrCode} alt="QR code for your authenticator app" className="qr" />
      <p className="break-all text-center font-mono text-xs text-ink-soft">{enrollment.secret}</p>
      <form action={confirm} className="space-y-4">
        <input type="hidden" name="factorId" value={enrollment.factorId} />
        <div>
          <label className="field-label" htmlFor="code">
            6-digit code
          </label>
          <input
            id="code"
            name="code"
            inputMode="numeric"
            autoComplete="one-time-code"
            pattern="\d{6}"
            maxLength={6}
            required
          />
        </div>
        {result?.error && <p className="text-sm text-danger">{result.error}</p>}
        <button className="btn btn-accent w-full" type="submit" disabled={confirming}>
          {confirming ? "Checking…" : "Turn on two-factor"}
        </button>
      </form>
    </div>
  );
}
